-- VB G-RAM-G additive business-logic upgrade.
-- Safe to run on the existing database: no existing rows are deleted or rewritten.
-- Historical payments remain intact. Allocation rows are created only for payments recorded after this migration.

create table if not exists public.payment_allocations (
  id bigint generated by default as identity primary key,
  payment_id bigint not null references public.payments_ledger(id) on delete restrict,
  work_id bigint not null references public.work_tracker(id) on delete restrict,
  amount numeric(14,2) not null check (amount > 0),
  created_at timestamptz not null default now(),
  unique(payment_id, work_id)
);
create index if not exists payment_allocations_work_idx on public.payment_allocations(work_id);
create index if not exists payment_allocations_payment_idx on public.payment_allocations(payment_id);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id text,
  action text not null check (action in ('INSERT','UPDATE','DELETE')),
  actor_id uuid,
  actor_email text,
  old_data jsonb,
  new_data jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_logs_created_idx on public.audit_logs(created_at desc);
create index if not exists audit_logs_record_idx on public.audit_logs(table_name, record_id);

alter table public.payment_allocations enable row level security;
alter table public.audit_logs enable row level security;

drop policy if exists "workspace read allocations" on public.payment_allocations;
create policy "workspace read allocations" on public.payment_allocations
for select to authenticated using (public.is_workspace_user());

drop policy if exists "workspace read audit logs" on public.audit_logs;
create policy "workspace read audit logs" on public.audit_logs
for select to authenticated using (public.is_workspace_user());

-- No direct client writes to allocation or audit history tables.
revoke insert, update, delete on public.payment_allocations from authenticated;
revoke insert, update, delete on public.audit_logs from authenticated;
grant select on public.payment_allocations, public.audit_logs to authenticated;
revoke insert, update, delete on public.payments_ledger from authenticated;
grant select on public.payments_ledger to authenticated;

create or replace function public.audit_row_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_record_id text;
begin
  if tg_op = 'INSERT' then
    v_new := to_jsonb(new);
    v_record_id := v_new ->> 'id';
  elsif tg_op = 'UPDATE' then
    v_old := to_jsonb(old);
    v_new := to_jsonb(new);
    v_record_id := coalesce(v_new ->> 'id', v_old ->> 'id');
  else
    v_old := to_jsonb(old);
    v_record_id := v_old ->> 'id';
  end if;

  insert into public.audit_logs(table_name, record_id, action, actor_id, actor_email, old_data, new_data)
  values (
    tg_table_name,
    v_record_id,
    tg_op,
    auth.uid(),
    coalesce(auth.jwt() ->> 'email', current_user),
    v_old,
    v_new
  );

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

drop trigger if exists audit_clients on public.clients;
create trigger audit_clients after insert or update or delete on public.clients
for each row execute function public.audit_row_change();

drop trigger if exists audit_work_tracker on public.work_tracker;
create trigger audit_work_tracker after insert or update or delete on public.work_tracker
for each row execute function public.audit_row_change();

drop trigger if exists audit_payments_ledger on public.payments_ledger;
create trigger audit_payments_ledger after insert or update or delete on public.payments_ledger
for each row execute function public.audit_row_change();

drop trigger if exists audit_payment_allocations on public.payment_allocations;
create trigger audit_payment_allocations after insert or update or delete on public.payment_allocations
for each row execute function public.audit_row_change();

-- Prevent edits to paid_amount outside the atomic payment-allocation workflow.
create or replace function public.guard_work_payment_amount()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' then
    if new.paid_amount is distinct from old.paid_amount
       and current_setting('app.payment_rpc', true) is distinct from 'on' then
      raise exception 'Paid amount can only be changed through the payment allocation workflow.';
    end if;
    if new.bill_amount < 0 or new.paid_amount < 0
       or ((new.bill_amount is distinct from old.bill_amount or new.paid_amount is distinct from old.paid_amount)
           and new.paid_amount > new.bill_amount) then
      raise exception 'Work bill and paid amounts are invalid.';
    end if;
  else
    if new.bill_amount < 0 or new.paid_amount < 0 or new.paid_amount > new.bill_amount then
      raise exception 'Work bill and paid amounts are invalid.';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists guard_work_payment_amount on public.work_tracker;
create trigger guard_work_payment_amount before insert or update on public.work_tracker
for each row execute function public.guard_work_payment_amount();

-- Validate new work assignments against the selected TA's assigned Gram Panchayat list.
-- Existing legacy work rows are not rewritten; unrelated edits to legacy rows remain possible.
create or replace function public.ta_has_gp_mapping(p_ta_name text, p_gp_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $
declare
  v_raw text;
  v_json jsonb;
begin
  select villages into v_raw
  from public.clients
  where lower(name) = lower(trim(p_ta_name))
  limit 1;

  if v_raw is null or nullif(trim(p_gp_name), '') is null then return false; end if;

  begin
    v_json := v_raw::jsonb;
    if jsonb_typeof(v_json) = 'array' then
      return exists (
        select 1
        from jsonb_array_elements(v_json) as items(value)
        where lower(coalesce(value ->> 'name', value ->> 'gp_name',
          case when jsonb_typeof(value) = 'string' then regexp_replace(trim(both '"' from value::text), '^[A-Z]{2}[0-9]{4,}\\s*[-–—|]\\s*', '', 'i') end, '')) = lower(trim(p_gp_name))
      );
    elsif jsonb_typeof(v_json) = 'object' then
      return lower(coalesce(v_json ->> 'name', v_json ->> 'gp_name', '')) = lower(trim(p_gp_name));
    end if;
  exception when others then
    v_json := null;
  end;

  return exists (
    select 1
    from regexp_split_to_table(v_raw, E'\\r?\\n') as raw_line
    where lower(trim(regexp_replace(raw_line, '^[A-Z]{2}[0-9]{4,}\\s*[-–—|]\\s*', '', 'i'))) = lower(trim(p_gp_name))
  );
end;
$;

create or replace function public.validate_work_assignment()
returns trigger
language plpgsql
security definer
set search_path = public
as $
begin
  if nullif(trim(new.work_name), '') is null then
    raise exception 'Work description is required.';
  end if;
  if new.bill_amount <= 0 then
    raise exception 'Work bill amount must be greater than zero.';
  end if;
  if new.received_date is not null and new.received_date > current_date then
    raise exception 'Work received date cannot be in the future.';
  end if;

  if tg_op = 'INSERT'
     or new.ta_name is distinct from old.ta_name
     or new.gp_name is distinct from old.gp_name then
    if nullif(trim(new.ta_name), '') is null
       or not public.ta_has_gp_mapping(new.ta_name, new.gp_name) then
      raise exception 'The selected Gram Panchayat is not assigned to this Technical Assistant.';
    end if;
  end if;
  return new;
end;
$;

drop trigger if exists validate_work_assignment on public.work_tracker;
create trigger validate_work_assignment before insert or update on public.work_tracker
for each row execute function public.validate_work_assignment();

-- A payment and all its allocations are committed together or not at all.
-- Outstanding works are allocated oldest-first. Work completion status is kept separate
-- from payment status and is never changed automatically by a payment.
create or replace function public.record_ta_payment(
  p_ta_name text,
  p_amount numeric,
  p_payment_date date,
  p_payment_mode text,
  p_reference_no text,
  p_depositing_operator text
)
returns table(payment_id bigint, allocated_amount numeric, remaining_amount numeric)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_work record;
  v_available numeric(14,2) := 0;
  v_remaining numeric(14,2);
  v_alloc numeric(14,2);
  v_payment_id bigint;
begin
  if auth.uid() is null or not public.is_workspace_user() then
    raise exception 'You are not authorized to record payments.';
  end if;
  if nullif(trim(p_ta_name), '') is null then raise exception 'Select a Technical Assistant.'; end if;
  if p_amount is null or p_amount <= 0 or round(p_amount, 2) <> p_amount then
    raise exception 'Enter a valid payment amount with up to two decimal places.';
  end if;
  if p_payment_date is null or p_payment_date > current_date then
    raise exception 'Payment date cannot be in the future.';
  end if;
  if nullif(trim(p_payment_mode), '') is null then raise exception 'Select a payment mode.'; end if;
  if nullif(trim(p_depositing_operator), '') is null then raise exception 'Enter the depositing operator.'; end if;
  if nullif(trim(p_reference_no), '') is not null then
    perform pg_advisory_xact_lock(hashtextextended(lower(trim(p_ta_name) || '|' || trim(p_reference_no)), 0));
    if exists (
      select 1 from public.payments_ledger
      where lower(ta_name) = lower(trim(p_ta_name))
        and lower(coalesce(reference_no, '')) = lower(trim(p_reference_no))
    ) then
      raise exception 'This payment reference is already recorded for this Technical Assistant.';
    end if;
  end if;

  -- Lock all outstanding works for this TA in deterministic order to avoid concurrent over-allocation.
  perform set_config('app.payment_rpc', 'on', true);
  for v_work in
    select id, bill_amount, paid_amount
    from public.work_tracker
    where ta_name = trim(p_ta_name) and bill_amount > paid_amount
    order by received_date nulls first, id
    for update
  loop
    v_available := v_available + greatest(0, v_work.bill_amount - v_work.paid_amount);
  end loop;

  if p_amount > v_available then
    raise exception 'Payment exceeds the current outstanding balance of %.', v_available;
  end if;

  insert into public.payments_ledger(ta_name, amount, payment_date, payment_mode, reference_no, depositing_operator)
  values (trim(p_ta_name), p_amount, p_payment_date, trim(p_payment_mode), nullif(trim(p_reference_no), ''), trim(p_depositing_operator))
  returning id into v_payment_id;

  v_remaining := p_amount;
  for v_work in
    select id, bill_amount, paid_amount
    from public.work_tracker
    where ta_name = trim(p_ta_name) and bill_amount > paid_amount
    order by received_date nulls first, id
    for update
  loop
    exit when v_remaining <= 0;
    v_alloc := least(v_remaining, greatest(0, v_work.bill_amount - v_work.paid_amount));
    if v_alloc > 0 then
      update public.work_tracker
      set paid_amount = paid_amount + v_alloc
      where id = v_work.id;
      insert into public.payment_allocations(payment_id, work_id, amount)
      values (v_payment_id, v_work.id, v_alloc);
      v_remaining := v_remaining - v_alloc;
    end if;
  end loop;

  return query select v_payment_id, p_amount - v_remaining, v_remaining;
end;
$$;

revoke all on function public.record_ta_payment(text,numeric,date,text,text,text) from public;
grant execute on function public.record_ta_payment(text,numeric,date,text,text,text) to authenticated;

