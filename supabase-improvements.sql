-- Prevent edits to paid_amount outside the atomic payment-allocation workflow.
create or replace function public.guard_work_payment_amount()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' then
    if new.paid_amount is distinct from old.paid_amount
       and current_setting('app.payment_rpc', true) is distinct from 'on' then
      raise exception 'Paid amount can only be changed through the payment allocation workflow.';
    end if;
    if new.bill_amount < 0 or new.paid_amount < 0
       or ((new.bill_amount is distinct from old.bill_amount or new.paid_amount is distinct from old.paid_amount)
           and new.paid_amount > new.bill_amount) then
      raise exception 'Work bill and paid amounts are invalid.';
    end if;
  else
    if new.bill_amount < 0 or new.paid_amount < 0 or new.paid_amount > new.bill_amount then
      raise exception 'Work bill and paid amounts are invalid.';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists guard_work_payment_amount on public.work_tracker;
create trigger guard_work_payment_amount before insert or update on public.work_tracker
for each row execute function public.guard_work_payment_amount();

-- Validate new work assignments against the selected TA's assigned Gram Panchayat list.
-- Existing legacy work rows are not rewritten; unrelated edits to legacy rows remain possible.
create or replace function public.ta_has_gp_mapping(p_ta_name text, p_gp_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_raw text;
  v_json jsonb;
begin
  select villages into v_raw
  from public.clients
  where lower(name) = lower(trim(p_ta_name))
  limit 1;

  if v_raw is null or nullif(trim(p_gp_name), '') is null then return false; end if;

  begin
    v_json := v_raw::jsonb;
    if jsonb_typeof(v_json) = 'array' then
      return exists (
        select 1
        from jsonb_array_elements(v_json) as items(gp_item)
        where lower(coalesce(gp_item ->> 'name', gp_item ->> 'gp_name',
          case when jsonb_typeof(gp_item) = 'string' then regexp_replace(trim(both '"' from gp_item::text), '^[A-Z]{2}[0-9]{4,}\s*[-–—|]\s*', '', 'i') end, '')) = lower(trim(p_gp_name))
      );
    elsif jsonb_typeof(v_json) = 'object' then
      return lower(coalesce(v_json ->> 'name', v_json ->> 'gp_name', '')) = lower(trim(p_gp_name));
    end if;
  exception when others then
    v_json := null;
  end;

  return exists (
    select 1
    from regexp_split_to_table(v_raw, E'\\r?\\n') as lines(line)
    where lower(trim(regexp_replace(line, '^[A-Z]{2}[0-9]{4,}\s*[-–—|]\s*', '', 'i'))) = lower(trim(p_gp_name))
  );
end;
$$;

revoke all on function public.ta_has_gp_mapping(text,text) from public;

create or replace function public.validate_work_assignment()
returns trigger
language plpgsql
security definer
set search_path = public
as $vbgramg$
begin
  -- This register only accepts work after it has been completed.
  new.status := 'Completed';
  if tg_op = 'INSERT' then
    if nullif(trim(new.work_name), '') is null then
      raise exception 'Work description is required.';
    end if;
    if new.bill_amount <= 0 then
      raise exception 'Work bill amount must be greater than zero.';
    end if;
    if new.received_date is not null and new.received_date > current_date then
      raise exception 'Work received date cannot be in the future.';
    end if;
  else
    if new.work_name is distinct from old.work_name and nullif(trim(new.work_name), '') is null then
      raise exception 'Work description is required.';
    end if;
    if new.bill_amount is distinct from old.bill_amount and new.bill_amount <= 0 then
      raise exception 'Work bill amount must be greater than zero.';
    end if;
    if new.received_date is distinct from old.received_date and new.received_date > current_date then
      raise exception 'Work received date cannot be in the future.';
    end if;
  end if;

  if tg_op = 'INSERT'
     or new.ta_name is distinct from old.ta_name
     or new.gp_name is distinct from old.gp_name then
    if nullif(trim(new.ta_name), '') is null
       or not public.ta_has_gp_mapping(new.ta_name, new.gp_name) then
      raise exception 'The selected Gram Panchayat is not assigned to this Technical Assistant.';
    end if;
  end if;
  return new;
end;
$vbgramg$;

