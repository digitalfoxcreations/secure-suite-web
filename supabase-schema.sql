-- Secure Suite V3 — Supabase schema
-- Run in Supabase SQL Editor. All application tables are protected by RLS.
-- Create users in Authentication > Users, then assign admin access below.

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('admin','operator')),
  created_at timestamptz not null default now()
);
create or replace function public.is_workspace_user()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.user_roles where user_id=auth.uid()) $$;

create table if not exists public.clients (
 id bigint generated by default as identity primary key,
 name text not null,
 post text,
 block text not null,
 phone text,
 villages text,
 created_at timestamptz not null default now()
);
create unique index if not exists clients_name_unique on public.clients(lower(name));

create table if not exists public.work_tracker (
 id bigint generated by default as identity primary key,
 work_name text not null,
 ta_name text not null,
 block_name text,
 gp_name text,
 status text not null default 'Pending' check(status in ('Pending','In Progress','Completed')),
 bill_amount numeric(14,2) not null default 300,
 paid_amount numeric(14,2) not null default 0,
 received_date date,
 estimate_number text,
 pdf_filename text,
 created_at timestamptz not null default now()
);
create index if not exists work_tracker_ta_idx on public.work_tracker(ta_name);
create index if not exists work_tracker_date_idx on public.work_tracker(received_date);

create table if not exists public.payments_ledger (
 id bigint generated by default as identity primary key,
 ta_name text not null,
 amount numeric(14,2) not null check(amount > 0),
 payment_date date not null,
 payment_mode text not null,
 reference_no text,
 depositing_operator text not null,
 created_at timestamptz not null default now()
);
create index if not exists payments_ledger_ta_idx on public.payments_ledger(ta_name);

alter table public.user_roles enable row level security;
alter table public.clients enable row level security;
alter table public.work_tracker enable row level security;
alter table public.payments_ledger enable row level security;

-- Users can read their own role; workspace tables are accessible only to assigned users.
drop policy if exists "read own role" on public.user_roles;
create policy "read own role" on public.user_roles for select to authenticated using(user_id=auth.uid());
do $$ declare t text; begin
 foreach t in array array['clients','work_tracker','payments_ledger'] loop
  execute format('drop policy if exists "workspace access" on public.%I',t);
  execute format('create policy "workspace access" on public.%I for all to authenticated using(public.is_workspace_user()) with check(public.is_workspace_user())',t);
 end loop;
end $$;

-- Estimate PDF storage bucket. Private bucket; signed URLs should be used for downloads.
